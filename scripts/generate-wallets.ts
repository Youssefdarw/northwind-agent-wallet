/**
 * Phase 1: generate the treasury wallet + one wallet per merchant.
 *
 * - Writes keys to .env (gitignored, chmod 600). Never prints them.
 * - Idempotent: wallets already in .env are KEPT (so you don't lose faucet funds);
 *   only missing ones are created. Other .env lines (e.g. ANTHROPIC_API_KEY) are preserved.
 */
import { existsSync, readFileSync, writeFileSync, chmodSync } from "node:fs";
import { execSync } from "node:child_process";
import { resolve } from "node:path";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";
import { assertTestnetConfig, addressUrl } from "../src/config/network.js";
import { WALLET_ROLES } from "../src/config/wallets.js";

assertTestnetConfig();

const envPath = resolve(process.cwd(), ".env");

// Safety: make sure .env is gitignored before we put secrets in it.
try {
  execSync("git check-ignore -q .env", { stdio: "ignore" });
} catch {
  console.error("✗ .env is not gitignored. Refusing to write private keys. Fix .gitignore first.");
  process.exit(1);
}

const existing = existsSync(envPath) ? readFileSync(envPath, "utf8") : "";
const lines = existing.split("\n");
const getVar = (name: string) =>
  lines.find((l) => l.startsWith(`${name}=`))?.slice(name.length + 1).trim();

const out: string[] = [];
const created: string[] = [];

out.push("# ── Northwind Industrial agent wallet · Base Sepolia TESTNET ONLY ──");
out.push("# Generated by scripts/generate-wallets.ts. Never commit this file.");
out.push("");

for (const r of WALLET_ROLES) {
  let pk = getVar(`${r.env}_PRIVATE_KEY`);
  if (!pk) {
    pk = generatePrivateKey();
    created.push(r.label);
  }
  const address = privateKeyToAccount(pk as `0x${string}`).address;
  out.push(`# ${r.label}`);
  out.push(`${r.env}_PRIVATE_KEY=${pk}`);
  out.push(`${r.env}_ADDRESS=${address}`);
  out.push("");
}

// Preserve any other variables the user added (API keys, RPC URL, etc.).
const managed = new Set(WALLET_ROLES.flatMap((r) => [`${r.env}_PRIVATE_KEY`, `${r.env}_ADDRESS`]));
const extras = lines.filter((l) => {
  const name = l.split("=")[0]?.trim();
  return l.includes("=") && !l.trim().startsWith("#") && !managed.has(name);
});
if (extras.length) {
  out.push("# Other settings");
  out.push(...extras);
  out.push("");
}

writeFileSync(envPath, out.join("\n"));
chmodSync(envPath, 0o600);

console.log(created.length ? `Created ${created.length} new wallet(s).` : "All wallets already existed. Kept them.");
console.log("Keys are in .env (gitignored, chmod 600). Addresses:\n");
for (const r of WALLET_ROLES) {
  const pk = out.find((l) => l.startsWith(`${r.env}_PRIVATE_KEY=`))!.split("=")[1] as `0x${string}`;
  const addr = privateKeyToAccount(pk).address;
  console.log(`  ${r.label.padEnd(32)} ${addr}`);
}
const treasury = privateKeyToAccount(
  out.find((l) => l.startsWith("TREASURY_PRIVATE_KEY="))!.split("=")[1] as `0x${string}`,
).address;
console.log(`\nFund the treasury with test USDC → ${treasury}`);
console.log(`View it on BaseScan → ${addressUrl(treasury)}`);
