/** Merchants the owner added from the dashboard (data/custom-merchants.json). Addresses only; keys stay in .env. */
export const CUSTOM_MERCHANTS_PATH = resolve(DATA_DIR, "custom-merchants.json");
export const loadCustomMerchants = (): Merchant[] => readJson<Merchant[]>(CUSTOM_MERCHANTS_PATH, []);

/** Every merchant: the built-in six plus any the owner added. Read fresh each call. */
export const getMerchants = (): Merchant[] => [...BUILTIN_MERCHANTS, ...loadCustomMerchants()];

/** Suppliers only (not uploaded invoices linked to a supplier on file). These are what the allowlist lists. */
export const getVendors = (): Merchant[] => getMerchants().filter((m) => !m.vendorId);

/** The supplier identity a bill is evaluated as (allowlist, known wallet, history). */
export const vendorIdOf = (m: Merchant): string => m.vendorId ?? m.id;

export const getMerchant = (id: string): Merchant => {
  const all = getMerchants();
  const m = all.find((x) => x.id === id);
  if (!m) throw new Error(`Unknown merchant "${id}". Known: ${all.map((x) => x.id).join(", ")}`);
  return m;
};

/** When a bill is due (YYYY-MM-DD), or null. Built-in bills fall due on a fixed day of the current month. */
export function dueDateOf(m: Merchant, now = new Date()): string | null {
  if (m.upload) return m.upload.dueDate;
  if (!m.dueDay) return null;
  const y = now.getFullYear(), mo = String(now.getMonth() + 1).padStart(2, "0");
  return `${y}-${mo}-${String(m.dueDay).padStart(2, "0")}`;
}

/** The only wallet a merchant is ever paid at. */
export const merchantAddress = (m: Merchant): Address => m.payTo ?? getAddressFor(m.id as WalletRoleId);

/** The wallet on file for a supplier (what the allowlist entry is pinned to). */
export const knownVendorAddress = (vendorId: string): Address => merchantAddress(getMerchant(vendorId));

/** Pay-per-use calls are paid unscaled; invoices and subscriptions are scaled by DEMO_SCALE. */
export const isScaled = (billType: BillType) => billType !== "pay_per_use";

/** Real-world USD → on-chain USDC atomic units (6 decimals) for ONE payment. */
export function usdToOnChainAtomic(amountUsd: number, billType: BillType, scale = DEMO_SCALE): bigint {
  const usd = isScaled(billType) ? amountUsd * scale : amountUsd;
  const atomic = Math.round(usd * 10 ** USDC_DECIMALS);
  if (atomic <= 0) throw new Error(`On-chain amount for $${amountUsd} rounds to zero at scale ${scale}`);
  return BigInt(atomic);
}

/** On-chain amount for ONE payment to this merchant, in USDC atomic units (6 decimals). */
export const onChainAtomic = (m: Merchant): bigint => usdToOnChainAtomic(m.amountUsd, m.billType);

/**
 * Build the policy input from what the MERCHANT presents (its invoice JSON) —
 * amount, payee and network come from the invoice, never from the LLM.
 */
export function requestFromInvoice(
  inv: {
    merchantId: string;
    merchant: string;
    payTo: string;
    network: string;
    billType: BillType;
    amountUsd: number;
    invoiceNumber: string;
    expectedCalls?: number;
    poNumber?: string;
  },
  purpose: string,
  calls?: number,
): PaymentRequest {
  return {
    merchantId: inv.merchantId,
    merchantName: inv.merchant,
    payTo: inv.payTo,
    network: inv.network,
    billType: inv.billType,
    amountUsd: inv.amountUsd,
    calls: inv.billType === "pay_per_use" ? (calls ?? inv.expectedCalls ?? 1) : undefined,
    invoiceNumber: inv.invoiceNumber,
    poNumber: inv.poNumber || undefined,
    purpose,
  };
}

export const atomicToUsdc =(a: bigint) => formatUnits(a, USDC_DECIMALS);

export const merchantUrl = (m: Merchant, path = m.paidPath) => `${MERCHANT_HOST}:${m.port}${path}`;

/** "$4,850 invoice → 4.85 test USDC on-chain" */
export function amountLabel(m: Merchant): string {
  const usd = m.amountUsd.toLocaleString("en-US", { style: "currency", currency: "USD", maximumFractionDigits: 2 });
  const what = m.billType === "pay_per_use" ? "per call" : m.billType === "subscription" ? "subscription" : "invoice";
  return `${usd} ${what} → ${atomicToUsdc(onChainAtomic(m))} test USDC on-chain`;
}
