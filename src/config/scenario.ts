import { DATA_DIR, readJson } from "../store/json.js";

export const DEMO_SCALE = (() => {
  const raw = process.env.DEMO_SCALE ?? "0.0001";
  const n = Number(raw);
  if (!Number.isFinite(n) || n <= 0 || n > 0.01) {
    throw new Error(`DEMO_SCALE must be in (0, 0.01]; got "${raw}"`);
  }
  return n;
})();

