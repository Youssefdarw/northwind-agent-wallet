/**
 * Northwind Industrial's monthly bills: the demo scenario.
 *
 * Amounts are in real-world USD. What actually moves on-chain is
 *   invoice USD × DEMO_SCALE   (e.g. $4,850 → 0.485 test USDC at the default scale 0.0001)
 * except pay-per-use API calls, which are paid unscaled ($0.01 → 0.01 test USDC),
 * because scaling them would round to dust below USDC's 6-decimal precision.
 */
import "dotenv/config";
import { formatUnits } from "viem";
import { USDC_DECIMALS } from "./network.js";
import { resolve } from "node:path";
import type { Address } from "viem";
