export interface UploadInfo {
  fileName: string;
  uploadedAt: string;
  language: string;
  invoiceDate: string | null;
  dueDate: string | null;
  lineItems: { description: string; quantity: number | null; unitPrice: number | null; amount: number | null }[];
  /** Text in the document aimed at an AI or the payer (verbatim). */
  suspiciousInstructions: string[];
  /** Claude's notes for the owner (advisory only; never read by the policy). */
  reviewNotes: string[];
  /** Deterministic checks computed from the extracted numbers. */
  computedNotes: string[];
  summaryEn: string;
  summaryAr: string;
  /** Wallet / bank details printed on the invoice, if any. */
  statedWallet: string | null;
  statedBankDetails: string | null;
}

export interface Merchant {
  /** Built-in ids match a wallet role in .env; owner-added merchants start with "custom_". */
  id: string;
  name: string;
  domain: string;
  port: number;
  billType: BillType;
  /** Invoice amount in real-world USD (for pay-per-use: price per call). */
  amountUsd: number;
  /** Pay-per-use only: expected number of calls this month. */
  expectedCalls?: number;
  invoiceNumber: string;
  /** Free-text line item description, exactly as the merchant presents it (untrusted!). */
  description: string;
  /** Path of the x402-protected endpoint. */
  paidPath: string;
  /** Purchase order this invoice references (e.g. "PO-TEST-02"). */
  poNumber?: string;
  /** Built-in bills: day of the current month the bill is due (uploads use upload.dueDate). */
  dueDay?: number;
  /**
   * Uploaded invoices from a supplier already on file: that supplier's id. The bill is
   * evaluated as that supplier (allowlist, known wallet, history). Absent → this record IS a supplier.
   */
  vendorId?: string;
  /** Where this bill came from. */
  source?: "scenario" | "added" | "upload";
  /** Uploaded invoices only: what Claude read from the document (for display/audit). */
  upload?: UploadInfo;
  /** Owner-added/uploaded only: the wallet this bill pays. Generated by the system, or (uploads) the wallet the invoice asks for. */
  payTo?: Address;
  /** Owner-added merchants only. */
  custom?: true;
  /** Owner-added merchants only: put on the allowlist when the policy is reset. */
  allowlistByDefault?: boolean;
  addedAt?: string;
}

