import { describe, expect, it, beforeAll } from "vitest";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

// Isolated data dir: these tests never touch data/ or .env.
process.env.DATA_DIR = mkdtempSync(join(tmpdir(), "nw-custom-"));
let validateNewMerchant: typeof import("./custom.js").validateNewMerchant;
beforeAll(async () => {
  ({ validateNewMerchant } = await import("./custom.js"));
});

const ok = { name: "Atlas Service Egypt", domain: "atlas-service.example", billType: "invoice" as const, amountUsd: 750, allowlist: false };

describe("Add merchant validation", () => {
  it("accepts a normal supplier", () => {
    expect(validateNewMerchant(ok)).toEqual([]);
  });

  it("has no pay-to field at all: the wallet is always generated by the system", () => {
    // Extra fields are ignored by validation and never read by addCustomMerchant.
    expect(validateNewMerchant({ ...ok, payTo: "0x000000000000000000000000000000000000dEaD" } as never)).toEqual([]);
  });

  it.each([
    ["a bad domain", { domain: "not a domain" }, /Domain/],
    ["pay-per-use (not supported from the form)", { billType: "pay_per_use" }, /Bill type/],
    ["a negative amount", { amountUsd: -5 }, /Amount/],
    ["more than 2 decimals", { amountUsd: 10.123 }, /2 decimals/],
    ["a duplicate of a built-in merchant's domain", { domain: "fabrikam.example" }, /already exists/],
    ["a duplicate of a built-in merchant's name", { name: "Contoso Office" }, /already exists/],
    ["very long invoice text", { description: "x".repeat(301) }, /300/],
  ] as const)("rejects %s", (_label, over, msg) => {
    expect(validateNewMerchant({ ...ok, ...over } as never).join("; ")).toMatch(msg);
  });
});
